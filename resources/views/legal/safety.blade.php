    <p>Most people are here for the same reason you are. These tips help you spot the few who are not.</p>

    <h2>Never send money</h2>
    <ul>
        <li>Never send money, gift cards, crypto, or wire transfers to someone you met online — however urgent or sad the story (medical bills, customs fees, being stuck abroad, a military deployment, an “investment opportunity”).</li>
        <li>Never share bank details, your Social Security number, or passwords.</li>
        <li>If someone asks, report them here. You can also report to the FTC at <a href="https://reportfraud.ftc.gov" target="_blank" rel="noopener">reportfraud.ftc.gov</a> and the FBI at <a href="https://www.ic3.gov" target="_blank" rel="noopener">ic3.gov</a>.</li>
    </ul>

    <h2>Warning signs of a romance scam</h2>
    <ul>
        <li>They quickly profess strong feelings or want to “move off this app” to WhatsApp, Telegram or text.</li>
        <li>They always have an excuse not to video call or meet.</li>
        <li>Their photos look like a model’s or appear elsewhere online (try a reverse image search).</li>
        <li>Their story has inconsistencies, or they say they work overseas.</li>
    </ul>

    <h2>Protect your privacy</h2>
    <ul>
        <li>Keep chats here until you trust someone. Don’t share your home address, workplace or daily routine early on.</li>
        <li>Look for the blue verified badge — but remember it confirms photos, not intentions.</li>
    </ul>

    <h2>Meeting in person</h2>
    <ul>
        <li>Video chat first. Meet in a busy public place and arrange your own transport.</li>
        <li>Tell a friend where you are going and who you are meeting.</li>
        <li>Stay sober enough to make good decisions and keep your drink with you.</li>
        <li>Leave whenever you feel uncomfortable. If you are in danger, call <strong>911</strong>.</li>
    </ul>

    <h2>Get help</h2>
    <ul>
        <li>National Domestic Violence Hotline: 1-800-799-7233</li>
        <li>RAINN Sexual Assault Hotline: 1-800-656-4673</li>
        <li>988 Suicide &amp; Crisis Lifeline: call or text 988</li>
    </ul>
